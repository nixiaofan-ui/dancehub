export const CN_CITIES = new Set(CN_CITY_LIST);

/**
 * 路名判据：命中说明前面那个城市名其实是条路。
 *   「北京中路银川文化城」的「北京」后面跟「中路」→ 路名，跳过；
 *   「广州越秀区中山五路」的「中山」后面跟「五路」→ 路名，跳过。
 * ⚠ 必须容忍数字与「大」：「中山五路」「中山东路」「中山大道」都真实存在，
 *   漏一个就会把广州的店判成中山（实测踩过 id 824）。
 */
const ROAD_TAIL = /^[东南西北中大小]?[一二三四五六七八九十百\d]{0,4}(?:路|街|道|巷)/;

/**
 * 地标后缀判据：城市名后面紧跟这些，说明它是「某某公园/广场」的一部分，不是城市。
 * 实测：上海某店的地址写「中山公园|长风大悦城|…」（没写「上海」），
 * 旧逻辑认了「中山」→ 上海的店被搬到中山。
 * ⚠ 「城」不在表里：「银川文化城」是真地名，得认。
 */
const LANDMARK_TAIL =
  /^(?:公园|广场|大厦|大楼|中心|酒店|宾馆|饭店|医院|学校|大学|学院|市场|商场|超市|银行|地铁|车站|机场|码头|书店|影院|影城)/;

/**
 * 城市名的前缀边界：前面必须是地址开头、非汉字（标点/空格/数字），
 * 或行政区划/道路后缀字。
 * ⚠ 不加这条，「石楼镇**亚运城**碧乐时光」里的「运城」（山西）会命中 ——
 *   实测踩过（id fityun-11059281，配置本来是东莞）。
 * ⚠ 也因此必须容忍「路银川」「省长春」这类：地址里城市名常紧跟在
 *   「省 / 路」后面，前面不可能是标点。
 */
const CITY_PREFIX_BOUNDARY = /(?:^|[^\u4e00-\u9fa5]|[省市区县镇乡村路街道巷号弄组队栋幢])$/;

/**
 * 「XX市」形态。必须带前缀边界，否则 `([\u4e00-\u9fa5]{2,4})市` 会把
 * 「吉林省长春市」匹成「林省长春」（贪婪吃掉 4 个字，恰好以「市」结尾），
 * 白名单对不上 → 整条地址白白漏掉一个真城市（实测：长春的店被抽成吉林）。
 */
const CITY_SUFFIX_RE =
  /(?:^|[^\u4e00-\u9fa5]|[省市区县镇乡村路街道巷号弄组队栋幢])([\u4e00-\u9fa5]{2,4})市/g;

/**
 * 从地址里抽城市名。抽不出返回 null。
 *
 * 两档：
 *  ①「XX市」——最常见的写法，取「市」前 2~4 字（带前缀边界），白名单对上才算；
 *  ② 裸名 —— 地址没写「市」但直接出现城市名（如「北京中路银川文化城」）。
 *     命中必须同时满足三条：前缀是边界（不是「亚运城」那种嵌在词里）、
 *     后面不跟路名（「中山五路」）、后面不跟地标词（「中山公园」）。
 *     多个候选取**位置上最靠前**的 —— 规范地址以「市/区」开头。
 *
 * @param {string} address
 * @returns {string|null} 城市名（不带「市」后缀）
 */
export function cityFromAddress(address) {
  const a = String(address || "").trim();
  if (!a) return null;

  // ① 「XX市」
  // ⚠ CITY_SUFFIX_RE 带 `g` 是模块级的：不重置 lastIndex，第二次调用会从
  //   上次的匹配位置往后找、直接漏掉前半段（经典的全局正则复用坑）。
  CITY_SUFFIX_RE.lastIndex = 0;
  let m;
  while ((m = CITY_SUFFIX_RE.exec(a)) !== null) {
    if (CN_CITIES.has(m[1])) return m[1];
  }

  // ② 裸名
  let best = null;
  let bestIdx = Number.POSITIVE_INFINITY;
  for (const city of CN_CITIES) {
    let idx = a.indexOf(city);
    while (idx !== -1) {
      const tail = a.slice(idx + city.length);
      const head = a.slice(0, idx);
      if (
        !ROAD_TAIL.test(tail) &&
        !LANDMARK_TAIL.test(tail) &&
        CITY_PREFIX_BOUNDARY.test(head) &&
        idx < bestIdx
      ) {
        best = city;
        bestIdx = idx;
      }
      idx = a.indexOf(city, idx + 1);
    }
  }
  return best;
}
