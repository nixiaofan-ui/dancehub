export const CN_CITIES = new Set(CN_CITY_LIST);

/**
 * 路名判据：命中说明前面那个城市名其实是条路。
 * 「北京中路银川文化城」里的「北京」后面跟「中路」→ 是路名，跳过；
 * 「银川」后面跟「文化城」→ 是城市，采用。
 */
const ROAD_TAIL = /^(?:[东南西北中]?[路街道巷]|大街)/;

/**
 * 从地址里抽城市名。抽不出返回 null。
 *
 * 两档：
 *  ①「XX市」——最常见的写法，直接取「市」前 2~4 字，白名单对上才算；
 *  ② 裸名 —— 地址没写「市」但直接出现城市名（如「北京中路银川文化城」）。
 *     取**最后一个**白名单命中，并排除「银川」被当成「XX路」的情形：
 *     若命中后面紧跟「路/街/道/巷」或「方位+路」，说明那是条路名，跳过。
 *
 * @param {string} address
 * @returns {string|null} 城市名（不带「市」后缀）
 */
export function cityFromAddress(address) {
  const a = String(address || "").trim();
  if (!a) return null;

  // ① 「XX市」
  const re = /([\u4e00-\u9fa5]{2,4})市/g;
  let m;
  while ((m = re.exec(a)) !== null) {
    if (CN_CITIES.has(m[1])) return m[1];
  }

  // ② 裸名：找所有白名单命中，取**位置上最靠后**且不像路名的那个
  //    （「XX路 + 真城市名」的地址里，城市名通常写在路名后面）
  let best = null;
  let bestIdx = -1;
  for (const city of CN_CITIES) {
    let idx = a.indexOf(city);
    while (idx !== -1) {
      if (!ROAD_TAIL.test(a.slice(idx + city.length)) && idx > bestIdx) {
        best = city;
        bestIdx = idx;
      }
      idx = a.indexOf(city, idx + 1);
    }
  }
  return best;
}
