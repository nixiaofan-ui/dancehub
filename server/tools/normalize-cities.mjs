const list = JSON.parse(fs.readFileSync(CFG, "utf8"));
const unmapped = new Set();
let changed = 0;
for (const c of list) {
  const city = c.studio.city;
  if (!/^\d+$/.test(String(city))) continue;
  const zh = CODE[city];
  if (!zh) { unmapped.add(String(city)); continue; }
  c.studio.city = zh;
  if (c.label) c.label = c.label.replace(/\(|（/g, "").trim();
  changed++;
}
if (!DRY && changed) fs.writeFileSync(CFG, JSON.stringify(list, null, 2) + "\n");
console.log(`规范化 ${changed} 条；未映射 ${unmapped.size} 个：${[...unmapped].join(", ") || "无"}${DRY ? "（dry，未写入）" : ""}`);

